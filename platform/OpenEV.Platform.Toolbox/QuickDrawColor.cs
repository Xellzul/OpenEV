namespace OpenEV.Platform.Toolbox;

// Classic Inside-Macintosh QuickDraw colorConstants — the indices passed to
// ForeColor/BackColor (resolved by MacToolbox.MapQuickDrawColorIndex).
public static class QuickDrawColor
{
    public const int Black   = 0x21;   // blackColor (33)
    public const int White   = 0x1e;   // whiteColor (30)
    public const int Red     = 0xcd;   // redColor (205)
    public const int Green   = 0x155;  // greenColor (341)
    public const int Cyan    = 0x111;  // cyanColor (273)
    public const int Blue    = 0x199;  // blueColor (409)
    public const int Magenta = 0x89;   // magentaColor (137)
    public const int Yellow  = 0x45;   // yellowColor (69)
}
